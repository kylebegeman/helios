// The reservation survives source cleanup and binds recovery to this kernel
// operation. It retains the declared manifest, never the sealed secret store.
type deploySourceReservation struct {
	Input     DeployInput       `json:"input"`
	Manifest  manifest.Manifest `json:"manifest"`
	Hash      string            `json:"source_sha256"`
	Commit    string            `json:"commit,omitempty"`
	Operation string            `json:"operation"`
	Discarded bool              `json:"discarded,omitempty"`
}

func deploySourceReservationPath(stateDir string, in DeployInput) string {
	hash := sha256.Sum256([]byte(in.Source + "\x00" + in.Revision + "\x00" + in.Manifest))
	return filepath.Join(stateDir, "builds", ".pending", hex.EncodeToString(hash[:])+".json")
}

func deploySourceDir(stateDir, app, revision string) string {
	return filepath.Join(stateDir, "builds", app, "deploy-"+revision)
}

func readDeploySourceReservation(stateDir string, in DeployInput) (*deploySourceReservation, error) {
	path := deploySourceReservationPath(stateDir, in)
	info, err := os.Lstat(path)
	if errors.Is(err, os.ErrNotExist) {
		return nil, nil
	}
	if err != nil {
		return nil, err
	}
	if !info.Mode().IsRegular() {
		return nil, errors.New("deploy source reservation must be a plain file")
	}
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	var stored deploySourceReservation
	if err := json.Unmarshal(data, &stored); err != nil {
		return nil, fmt.Errorf("read captured deploy source: %w", err)
	}
	asked, _ := json.Marshal(in)
	pinned, _ := json.Marshal(stored.Input)
	if !bytes.Equal(asked, pinned) || !fullSnapshotID.MatchString(stored.Hash) {
		return nil, errors.New("deploy source reservation does not match this request")
	}
	if err := stored.Manifest.Validate(); err != nil {
		return nil, err
	}
	return &stored, nil
}

func sourceWithin(root, path string) bool {
	relative, err := filepath.Rel(root, path)
	return err == nil && relative != ".." && !strings.HasPrefix(relative, ".."+string(filepath.Separator)) && !filepath.IsAbs(relative)
}

// Resolve existing ancestors too: a configured state path may reach the
// source through a symlink even before its builds directory exists.
func deployPathLocation(path string) (string, error) {
	absolute, err := filepath.Abs(path)
	if err != nil {
		return "", err
	}
	current := absolute
	var suffix []string
	for {
		resolved, err := filepath.EvalSymlinks(current)
		if err == nil {
			for i := len(suffix) - 1; i >= 0; i-- {
				resolved = filepath.Join(resolved, suffix[i])
			}
			return resolved, nil
		}
		if !errors.Is(err, os.ErrNotExist) {
			return "", err
		}
		parent := filepath.Dir(current)
		if parent == current {
			return "", err
		}
		suffix = append(suffix, filepath.Base(current))
		current = parent
	}
}

func refuseRecursiveDeployCapture(source, stateDir string) error {
	root, err := deployPathLocation(source)
	if err != nil {
		return err
	}
	capture, err := deployPathLocation(filepath.Join(stateDir, "builds"))
	if err != nil {
		return err
	}
	if sourceWithin(root, capture) {
		return errors.New("deploy source includes helios's build captures; choose a source outside the state directory")
	}
	return nil
}

// sourceLink keeps the link itself, never reads through it, and refuses a link
// that could make a build or database init read uncaptured external bytes.
func sourceLink(root *os.Root, path string) (string, error) {
	link, err := root.Readlink(path)
	if err != nil {
		return "", err
	}
	if err := validateSourceLink(root, path, link); err != nil {
		return "", err
	}
	return link, nil
}

// Resolve each component before processing .., including links in ancestors.
// Missing components may be generated by a build, so safe dangling links stay.
func validateSourceLink(root *os.Root, path, link string) error {
	outside := func() error { return fmt.Errorf("deploy source link %s leads outside its source tree", path) }
	if filepath.IsAbs(link) {
		return outside()
	}
	remaining := strings.Split(filepath.Dir(path)+string(filepath.Separator)+link, string(filepath.Separator))
	var resolved []string
	links := 0
	for len(remaining) > 0 {
		component := remaining[0]
		remaining = remaining[1:]
		switch component {
		case "", ".":
			continue
		case "..":
			if len(resolved) == 0 {
				return outside()
			}
			resolved = resolved[:len(resolved)-1]
			continue
		}
		candidate := filepath.Join(append(append([]string{}, resolved...), component)...)
		info, err := root.Lstat(candidate)
		if errors.Is(err, os.ErrNotExist) {
			resolved = append(resolved, component)
			continue
		}
		if err != nil {
			return fmt.Errorf("resolve deploy source link %s: %w", path, err)
		}
		if info.Mode()&os.ModeSymlink == 0 {
			resolved = append(resolved, component)
			continue
		}
		links++
		if links > 255 {
			return fmt.Errorf("deploy source link %s contains a link cycle", path)
		}
		target, err := root.Readlink(candidate)
		if err != nil {
			return err
		}
		if filepath.IsAbs(target) {
			return outside()
		}
		remaining = append(strings.Split(target, string(filepath.Separator)), remaining...)
	}
	return nil
}

// Refuse swapped links and special files before any read can block or consume
// data outside the entry that was inspected. The Root also bounds ancestors.
func openDeploySourceFile(root *os.Root, path string, inspected fs.FileInfo) (*os.File, error) {
	file, err := root.OpenFile(path, os.O_RDONLY|unix.O_NOFOLLOW|unix.O_NONBLOCK, 0)
	if err != nil {
		return nil, err
	}
	opened, err := file.Stat()
	if err != nil || !opened.Mode().IsRegular() || !os.SameFile(inspected, opened) {
		file.Close()
		if err != nil {
			return nil, err
		}
		return nil, errors.New("deploy source changed while its file was opened")
	}
	return file, nil
}

func deploySourceHash(ctx context.Context, root string) (string, error) {
	info, err := os.Lstat(root)
	if err != nil {
		return "", err
	}
	if !info.IsDir() {
		return "", errors.New("deploy source must be a plain directory")
	}
	bounded, err := os.OpenRoot(root)
	if err != nil {
		return "", err
	}
	defer bounded.Close()
	opened, err := bounded.Stat(".")
	if err != nil {
		return "", err
	}
	if !os.SameFile(info, opened) {
		return "", errors.New("deploy source changed while it was opened")
	}
	hash := sha256.New()
	fmt.Fprintf(hash, "root:%o:", info.Mode().Perm())
	err = fs.WalkDir(bounded.FS(), ".", func(path string, entry fs.DirEntry, walkErr error) error {
		if walkErr != nil {
			return walkErr
		}
		if err := ctx.Err(); err != nil {
			return err
		}
		relative := filepath.FromSlash(path)
		if relative == "." {
			return nil
		}
		info, err := bounded.Lstat(relative)
		if err != nil {
			return err
		}
		fmt.Fprintf(hash, "%d:%s:%o:", len(relative), relative, info.Mode())
		if entry.IsDir() {
			return nil
		}
		if info.Mode()&os.ModeSymlink != 0 {
			link, err := sourceLink(bounded, relative)
			if err != nil {
				return err
			}
			fmt.Fprintf(hash, "%d:%s", len(link), link)
			return nil
		}
		if !info.Mode().IsRegular() {
			return fmt.Errorf("deploy source %s is not a plain file or safe relative link", relative)
		}
		fmt.Fprintf(hash, "%d:", info.Size())
		file, err := openDeploySourceFile(bounded, relative, info)
		if err != nil {
			return err
		}
		copied, copyErr := io.Copy(hash, io.LimitReader(file, info.Size()+1))
		closeErr := file.Close()
		if copied != info.Size() {
			return errors.New("deploy source changed while it was being hashed")
		}
		return errors.Join(copyErr, closeErr)
	})
	if err != nil {
		return "", err
	}
	return hex.EncodeToString(hash.Sum(nil)), nil
}

func copyDeploySource(ctx context.Context, from, to string) error {
	type directory struct {
		path string
		mode fs.FileMode
	}
	var directories []directory
	info, err := os.Lstat(from)
	if err != nil {
		return err
	}
	if !info.IsDir() {
		return errors.New("deploy source must be a plain directory")
	}
	bounded, err := os.OpenRoot(from)
	if err != nil {
		return err
	}
	defer bounded.Close()
	opened, err := bounded.Stat(".")
	if err != nil {
		return err
	}
	if !os.SameFile(info, opened) {
		return errors.New("deploy source changed while it was opened")
	}
	err = fs.WalkDir(bounded.FS(), ".", func(path string, entry fs.DirEntry, walkErr error) error {
		if walkErr != nil {
			return walkErr
		}
		if err := ctx.Err(); err != nil {
			return err
		}
		relative := filepath.FromSlash(path)
		destination := filepath.Join(to, relative)
		info, err := bounded.Lstat(relative)
		if err != nil {
			return err
		}
		if entry.IsDir() {
			if err := os.MkdirAll(destination, 0700); err != nil {
				return err
			}
			directories = append(directories, directory{destination, info.Mode().Perm()})
			return nil
		}
		if info.Mode()&os.ModeSymlink != 0 {
			link, err := sourceLink(bounded, relative)
			if err != nil {
				return err
			}
			return os.Symlink(link, destination)
		}
		if !info.Mode().IsRegular() {
			return fmt.Errorf("deploy source %s is not a plain file or safe relative link", relative)
		}
		source, err := openDeploySourceFile(bounded, relative, info)
		if err != nil {
			return err
		}
		dest, err := os.OpenFile(destination, os.O_CREATE|os.O_EXCL|os.O_WRONLY, 0600)
		if err != nil {
			source.Close()
			return err
		}
		copied, copyErr := io.Copy(dest, io.LimitReader(source, info.Size()+1))
		if copied != info.Size() {
			copyErr = errors.Join(copyErr, errors.New("deploy source changed while it was copied"))
		}
		modeErr := dest.Chmod(info.Mode().Perm())
		syncErr := dest.Sync()
		return errors.Join(copyErr, modeErr, syncErr, dest.Close(), source.Close())
	})
	if err != nil {
		return err
	}
	for i := len(directories) - 1; i >= 0; i-- {
		if err := os.Chmod(directories[i].path, directories[i].mode); err != nil {
			return err
		}
		if err := syncMigrationDir(directories[i].path); err != nil {
			return err
		}
	}
	return nil
}

// Leave the same minimum free space used by disk observation so a source
// capture cannot consume the room needed by running workloads and backups.
const deployCaptureFreeMin = 5 << 30

func deploySourceStorage(ctx context.Context, source string, block uint64) (uint64, error) {
	root, err := os.OpenRoot(source)
	if err != nil {
		return 0, err
	}
	defer root.Close()
	var total uint64
	err = fs.WalkDir(root.FS(), ".", func(path string, entry fs.DirEntry, walkErr error) error {
		if walkErr != nil {
			return walkErr
		}
		if err := ctx.Err(); err != nil {
			return err
		}
		info, err := root.Lstat(filepath.FromSlash(path))
		if err != nil {
			return err
		}
		size := uint64(max(info.Size(), 0))
		// Every copied entry needs metadata; plain files also allocate every
		// logical byte, including sparse input regions and hard-linked files.
		needed := block
		if info.Mode().IsRegular() {
			if size > math.MaxUint64-block {
				return errors.New("deploy source is too large to capture")
			}
			needed += ((size + block - 1) / block) * block
		}
		if needed > math.MaxUint64-total {
			return errors.New("deploy source is too large to capture")
		}
		total += needed
		return nil
	})
	return total, err
}

func deployCaptureBudget(required, available uint64) error {
	if available < deployCaptureFreeMin || required > available-deployCaptureFreeMin {
		return fmt.Errorf("capturing deploy source needs %s while preserving 5 GiB free; free disk space or run helios gc", HumanBytes(int64(min(required, math.MaxInt64))))
	}
	return nil
}

func checkDeployCaptureSpace(ctx context.Context, source, destination string) error {
	var disk unix.Statfs_t
	if err := unix.Statfs(destination, &disk); err != nil {
		return fmt.Errorf("inspect deploy capture disk space: %w", err)
	}
	block := uint64(disk.Bsize)
	if block == 0 || disk.Bavail > math.MaxUint64/block {
		return errors.New("invalid deploy capture disk capacity")
	}
	required, err := deploySourceStorage(ctx, source, block)
	if err != nil {
		return err
	}
	return deployCaptureBudget(required, disk.Bavail*block)
}

func deployCapturePlan(ctx context.Context, d Deploy, in DeployInput, m *manifest.Manifest, commit, hash string) (*kernel.Plan, error) {
	stateDir := d.StateDir
	if stateDir == "" {
		stateDir = defaultStateDir
	}
	source := deploySourceDir(stateDir, m.App, in.Revision)
	reservation := deploySourceReservationPath(stateDir, in)
	from := &buildFrom{source: filepath.Join(source, "source"), commit: commit, signer: in.Signer, restore: in.Restore, secretsFrom: in.SecretsFrom}
	plan, err := d.rollout(ctx, m, in.Revision, from)
	if err != nil {
		return nil, err
	}
	capture := kernel.Step{Name: "capture-source", Change: "capture approved source " + hash + " for " + m.App, Apply: func(ctx context.Context, out io.Writer) error {
		stored, err := readDeploySourceReservation(stateDir, in)
		if err != nil {
			return err
		}
		if stored != nil {
			if stored.Operation != kernel.OperationID(ctx) {
				return errors.New("captured deploy source belongs to another operation; choose a new revision")
			}
			if stored.Hash != hash || manifestDigest(&stored.Manifest) != manifestDigest(m) {
				return errors.New("captured deploy source identity changed; review deployment again")
			}
			if stored.Discarded {
				return errors.New("captured deploy source was already discarded; choose a new revision")
			}
			if _, err := os.Lstat(source); err == nil {
				got, err := deploySourceHash(ctx, from.source)
				if err != nil {
					return err
				}
				if got != hash {
					return errors.New("captured deploy source changed; refusing to build it")
				}
				return nil
			} else if !errors.Is(err, os.ErrNotExist) {
				return err
			}
		}
		got, err := deploySourceHash(ctx, in.Source)
		if err != nil {
			return err
		}
		if got != hash {
			return errors.New("deploy source changed after planning; review deployment again")
		}
		stored = &deploySourceReservation{Input: in, Manifest: *m, Hash: hash, Commit: commit, Operation: kernel.OperationID(ctx)}
		if err := writeRehearsalJSON(reservation, stored); err != nil {
			return err
		}
		parent := filepath.Dir(source)
		if err := os.MkdirAll(parent, 0700); err != nil {
			return err
		}
		identity := sha256.Sum256([]byte(stored.Operation))
		temp := source + ".tmp-" + hex.EncodeToString(identity[:16])
		if err := os.RemoveAll(temp); err != nil {
			return err
		}
		defer os.RemoveAll(temp)
		if err := checkDeployCaptureSpace(ctx, in.Source, parent); err != nil {
			return err
		}
		if err := os.Mkdir(temp, 0700); err != nil {
			return err
		}
		captured := filepath.Join(temp, "source")
		if err := copyDeploySource(ctx, in.Source, captured); err != nil {
			return err
		}
		got, err = deploySourceHash(ctx, captured)
		if err != nil {
			return err
		}
		if got != hash {
			return errors.New("deploy source changed while it was captured; review deployment again")
		}
		name := in.Manifest

		capturedManifest, err := manifest.LoadFile(captured, name)
		if err != nil {
			return err
		}
		if manifestDigest(capturedManifest) != manifestDigest(m) {
			return errors.New("deploy manifest changed while source was captured; review deployment again")
		}
		if err := syncMigrationDir(temp); err != nil {
			return err
		}
		if err := os.Rename(temp, source); err != nil {
			return err
		}
		if err := syncMigrationDir(parent); err != nil {
			return err
		}
		fmt.Fprintf(out, "captured approved source %s\n", hash)
		return nil
	}}
	plan.Steps = append([]kernel.Step{capture}, plan.Steps...)
	plan.Steps = append(plan.Steps, kernel.Step{Name: "discard-source", Change: "remove captured source after deployment", Apply: func(ctx context.Context, out io.Writer) error {
		stored, err := readDeploySourceReservation(stateDir, in)
		if err != nil {
			return err
		}
		if stored == nil || stored.Operation != kernel.OperationID(ctx) {
			return errors.New("captured deploy source belongs to another operation")
		}
		if err := os.RemoveAll(source); err != nil {
			return err
		}
		stored.Discarded = true
		if err := writeRehearsalJSON(reservation, stored); err != nil {
			return err
		}
		fmt.Fprintln(out, "captured source removed")
		return nil
	}})
	return plan, nil
}

func forgetDeploySourceReservations(stateDir, app string) error {
	dir := filepath.Join(stateDir, "builds", ".pending")
	entries, err := os.ReadDir(dir)
	if errors.Is(err, os.ErrNotExist) {
		return nil
	}
	if err != nil {
		return err
	}
	for _, entry := range entries {
		if !entry.Type().IsRegular() || !strings.HasSuffix(entry.Name(), ".json") {
			continue
		}
		path := filepath.Join(dir, entry.Name())
		data, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		var stored deploySourceReservation
		if err := json.Unmarshal(data, &stored); err != nil {
			return fmt.Errorf("read deploy source reservation %s: %w", entry.Name(), err)
		}
		if stored.Manifest.App == app {
			if err := os.Remove(path); err != nil {
				return err
			}
		}
	}
	return syncMigrationDir(dir)
}

// Only terminal owning operations release captures. Read every reservation
// first so another unfinished operation sharing a revision protects its tree.
func collectDeploySources(ctx context.Context, store *state.Store, stateDir string) (int, error) {
	dir := filepath.Join(stateDir, "builds", ".pending")
	entries, err := os.ReadDir(dir)
	if errors.Is(err, os.ErrNotExist) {
		return 0, nil
	}
	if err != nil {
		return 0, err
	}
	type candidate struct {
		path, source, temp string
		terminal           bool
	}
	var candidates []candidate
	protected := map[string]bool{}
	for _, entry := range entries {
		if !entry.Type().IsRegular() || !strings.HasSuffix(entry.Name(), ".json") {
			continue
		}
		path := filepath.Join(dir, entry.Name())
		data, err := os.ReadFile(path)
		if err != nil {
			return 0, err
		}
		var stored deploySourceReservation
		if err := json.Unmarshal(data, &stored); err != nil {
			return 0, err
		}
		checked, err := readDeploySourceReservation(stateDir, stored.Input)
		if err != nil {
			return 0, err
		}
		if checked == nil || path != deploySourceReservationPath(stateDir, stored.Input) || !revisionPattern.MatchString(stored.Input.Revision) {
			return 0, errors.New("invalid deploy source reservation during collection")
		}
		source := deploySourceDir(stateDir, stored.Manifest.App, stored.Input.Revision)
		terminal := false
		if stored.Operation != "" {
			op, _, err := store.Get(ctx, stored.Operation)
			if err != nil && !errors.Is(err, state.ErrNotFound) {
				return 0, err
			}
			if err == nil && op.Kind == DeployKind && op.Target == stored.Manifest.App {
				var input DeployInput
				if err := json.Unmarshal(op.Input, &input); err != nil {
					return 0, err
				}
				a, _ := json.Marshal(input)
				b, _ := json.Marshal(stored.Input)
				terminal = bytes.Equal(a, b) && op.Status.Final()
			}
		}
		identity := sha256.Sum256([]byte(stored.Operation))
		candidates = append(candidates, candidate{path: path, source: source, temp: source + ".tmp-" + hex.EncodeToString(identity[:16]), terminal: terminal})
		if !terminal {
			protected[source] = true
		}
	}
	removed := 0
	for _, candidate := range candidates {
		if !candidate.terminal {
			continue
		}
		if !protected[candidate.source] {
			if err := os.RemoveAll(candidate.source); err != nil {
				return removed, err
			}
		}
		if err := os.RemoveAll(candidate.temp); err != nil {
			return removed, err
		}
		if err := os.Remove(candidate.path); err != nil {
			return removed, err
		}
		removed++
	}
	if removed > 0 {
		return removed, syncMigrationDir(dir)
	}
	return removed, nil
}
